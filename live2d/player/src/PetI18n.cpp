void SetLangCode(const std::string& code)
{
    Lang l = Lang::Zh;
    if (code == "en") l = Lang::En;
    else if (code == "ja") l = Lang::Ja;
    else if (code == "auto")
    {
        for (const char* k : { "LC_ALL", "LC_MESSAGES", "LANG" })
        {
            const char* v = std::getenv(k);
            if (v == nullptr || *v == '\0' || std::string(v) == "C" || std::string(v) == "POSIX") continue;
            const std::string s = v;
            l = s.find("zh") != std::string::npos ? Lang::Zh : (s.find("ja") != std::string::npos ? Lang::Ja : Lang::En);
            break;
        }
    }
    if (l != g_lang) Missing().clear();
    g_lang = l;
}

Lang Get() { return g_lang; }

const char* Code()
{
    switch (g_lang)
    {
    case Lang::En: return "en";
    case Lang::Ja: return "ja";
    default: return "zh";
    }
}

const char* LangCn()
{
    switch (g_lang)
    {
    case Lang::En: return "英语";
    case Lang::Ja: return "日语";
    default: return "中文";
    }
}

/** 只把"含汉字且没进表"的当漏翻记录：纯 ASCII/标点（Zzz…、？！、动作 id）不算漏 */
static bool HasHan(const std::string& s)
{
    for (size_t i = 0; i + 2 < s.size(); ++i)
    {
        const unsigned char c = (unsigned char)s[i];
        if (c >= 0xE4 && c <= 0xE9 && ((unsigned char)s[i + 1] & 0xC0) == 0x80
            && ((unsigned char)s[i + 2] & 0xC0) == 0x80)
        {
            return true;
        }
    }
    return false;
}

std::string TF(const std::string& zh, std::initializer_list<std::string> args)
{
    if (g_lang != Lang::Zh)
    {
        const std::map<std::string, std::string>& m = MapFor(g_lang);
        const auto it = m.find(zh);
        if (it != m.end()) return Fill(it->second, args);
        if (HasHan(zh)) Missing().insert(zh);
    }
    return Fill(zh, args);
}

const std::string& MissingReport()
{
    static std::string s;
    s.clear();
    for (const std::string& k : Missing())
    {
        if (!s.empty()) s += "\n";
        s += k;
    }
    return s;
}

